@dataclass
class RawFile:
    """One dataset file, decoded but not yet resampled or windowed."""
    path: Path
    de: np.ndarray                     # drive-end accelerometer, (n,)
    fs: float                          # native sample rate, Hz
    fe: np.ndarray | None = None       # fan-end accelerometer, (m,)
    rpm: float | None = None           # from the file if present
    label: int = 0                     # 0 = healthy, 1 = faulty
    race: str | None = None            # "outer" / "inner" / "ball" / None
    fault_size_in: float | None = None
    load_hp: int | None = None
    rpm_source: str = "unknown"

    @property
    def duration_s(self) -> float:
        return len(self.de) / self.fs

    def describe(self) -> str:
        kind = "FAULTY" if self.label else "healthy"
        bits = [f"{self.path.name:<24}", f"{kind:<7}", f"{self.duration_s:6.2f} s",
                f"@{self.fs / 1000:g} kHz"]
        if self.rpm:
            bits.append(f"{self.rpm:7.1f} rpm ({self.rpm_source})")
        if self.race:
            sz = f" {self.fault_size_in:.3f}\"" if self.fault_size_in else ""
            bits.append(f"{self.race}{sz}")
        bits.append("DE+FE" if self.fe is not None else "DE only")
        return "  ".join(bits)


# CWRU normal-baseline files are numbered 97-100 (loads 0-3 hp). Every mirror
# either keeps those numbers or renames them to Normal_0..Normal_3.
_CWRU_NORMAL_NUMBERS = {"97", "98", "99", "100"}

# Fault-code prefixes used by essentially every CWRU mirror on GitHub/Kaggle.
#   IR007_1  = inner race, 0.007", 1 hp load
#   OR021@6_0 = outer race, 0.021", clock position 6, 0 hp
#   B014_2   = ball, 0.014", 2 hp
_FAULT_RE = re.compile(r"(?P<code>IR|OR|B)(?P<size>\d{3})", re.IGNORECASE)
_LOAD_RE = re.compile(r"_(?P<load>[0-3])(?:\D|$)")
_RACE_FROM_CODE = {"IR": "inner", "OR": "outer", "B": "ball"}


def classify_name(path: Path) -> dict:
    """Work out healthy/faulty, fault race, size and load from the filename.

    Filename heuristics are fragile, so the report ALWAYS prints the resulting
    classification table and the script refuses to run if it ends up with only
    one class. A silent misclassification here would produce a beautiful,
    meaningless AUC — the single most likely way for this script to lie.
    Override anything with a `manifest.csv` (see `load_manifest`).
    """
    stem = path.stem
    low = stem.lower()

    if (stem in _CWRU_NORMAL_NUMBERS
            or any(w in low for w in ("normal", "healthy", "baseline", "good"))):
        info = {"label": 0, "race": None, "fault_size_in": None}
    else:
        m = _FAULT_RE.search(stem)
        if m:
            info = {"label": 1,
                    "race": _RACE_FROM_CODE[m.group("code").upper()],
                    "fault_size_in": int(m.group("size")) / 1000.0}
        else:
            # Unrecognised name: call it faulty but flag it. Being wrong in
            # this direction costs us AUC (a healthy file counted as faulty
            # drags the score down); being wrong the other way would inflate
            # it. Always fail pessimistic.
            info = {"label": 1, "race": None, "fault_size_in": None}

    lm = _LOAD_RE.search(stem)
    info["load_hp"] = int(lm.group("load")) if lm else None
    return info


def load_manifest(data_dir: Path) -> dict[str, dict]:
    """Optional `manifest.csv` overriding the filename heuristics.

    Columns: filename,label,race,fault_size_in,load_hp,rpm
    `label` is 0/1 or the words healthy/faulty. Anything blank falls back to
    the heuristic. Write one the moment you doubt the auto-classification.
    """
    path = data_dir / "manifest.csv"
    if not path.exists():
        return {}
    out: dict[str, dict] = {}
    lines = [ln for ln in path.read_text().splitlines() if ln.strip()]
    header = [h.strip().lower() for h in lines[0].split(",")]
    for ln in lines[1:]:
        cells = [c.strip() for c in ln.split(",")]
        row = dict(zip(header, cells))
        name = row.get("filename", "")
        if not name:
            continue
        rec: dict = {}
        lab = row.get("label", "").lower()
        if lab:
            rec["label"] = 0 if lab in ("0", "healthy", "normal", "good") else 1
        for key, cast in (("race", str), ("fault_size_in", float),
                          ("load_hp", int), ("rpm", float)):
            if row.get(key):
                rec[key] = cast(row[key])
        out[name] = rec
    return out


def _first_key(d: dict, suffix: str) -> np.ndarray | None:
    """CWRU .mat variables are named X097_DE_time, X118_FE_time, X097RPM...
    The numeric prefix changes per file, so match on the suffix."""
    for k, v in d.items():
        if k.startswith("__"):
            continue
        if k.endswith(suffix):
            return np.asarray(v).squeeze().astype(np.float64)
    return None


def load_file(path: Path, default_fs: float) -> RawFile:
    """Decode one .mat / .npz / .csv into a RawFile. Format is chosen by
    extension so a student can drop in whichever mirror they downloaded."""
    ext = path.suffix.lower()
    fs = default_fs
    rpm = None

    if ext == ".mat":
        from scipy.io import loadmat
        d = loadmat(str(path))
        de = _first_key(d, "_DE_time")
        fe = _first_key(d, "_FE_time")
        rpm_arr = _first_key(d, "RPM")
        if rpm_arr is not None and rpm_arr.size:
            rpm = float(np.ravel(rpm_arr)[0])
        if de is None:
            # Some fan-end-only files have no DE channel at all. Fall back so
            # the file is still usable, and say so.
            de, fe = fe, None
        if de is None:
            raise ValueError(f"{path.name}: no *_DE_time or *_FE_time variable")

    elif ext == ".npz":
        z = np.load(path, allow_pickle=False)
        keys = {k.lower(): k for k in z.files}
        de = np.asarray(z[keys["de"]]).squeeze().astype(np.float64) if "de" in keys else None
        fe = np.asarray(z[keys["fe"]]).squeeze().astype(np.float64) if "fe" in keys else None
        if de is None:
            raise ValueError(f"{path.name}: npz has no 'de' array (has {z.files})")
        if "fs" in keys:
            fs = float(np.ravel(z[keys["fs"]])[0])
        if "rpm" in keys:
            rpm = float(np.ravel(z[keys["rpm"]])[0])

    elif ext == ".csv":
        arr = np.loadtxt(path, delimiter=",", skiprows=1)
        arr = arr.reshape(len(arr), -1)
        de = arr[:, 0].astype(np.float64)
        fe = arr[:, 1].astype(np.float64) if arr.shape[1] > 1 else None
    else:
        raise ValueError(f"{path.name}: unsupported extension {ext!r}")

    return RawFile(path=path, de=np.asarray(de, dtype=np.float64), fs=float(fs),
                   fe=None if fe is None else np.asarray(fe, dtype=np.float64),
                   rpm=rpm, rpm_source="file" if rpm else "unknown")


def discover(data_dir: Path, default_fs: float, verbose: bool = True) -> list[RawFile]:
    """Load every dataset file under data_dir (recursively) and label it."""
    manifest = load_manifest(data_dir)
    paths = sorted(p for p in data_dir.rglob("*")
                   if p.suffix.lower() in (".mat", ".npz", ".csv")
                   and p.name.lower() != "manifest.csv")
    files: list[RawFile] = []
    for p in paths:
        try:
            rf = load_file(p, default_fs)
        except Exception as e:                      # noqa: BLE001 — report, skip
            if verbose:
                print(f"  ! skipping {p.name}: {e}")
            continue
        info = {**classify_name(p), **manifest.get(p.name, {})}
        rf.label = int(info.get("label", 1))
        rf.race = info.get("race")
        rf.fault_size_in = info.get("fault_size_in")
        rf.load_hp = info.get("load_hp")
        if info.get("rpm"):
            rf.rpm, rf.rpm_source = float(info["rpm"]), "manifest"
        files.append(rf)
    return files


# ============================================================================
# 2. Resampling — the mismatch handled explicitly, never silently
# ============================================================================

def resample_to(x: np.ndarray, fs_in: float, fs_out: float) -> np.ndarray:
    """Polyphase resample with an anti-alias filter.

    resample_poly, not scipy.signal.resample: the latter is FFT-based and
    assumes the signal is periodic in the window, which smears energy from the
    discontinuity at the wrap point across the whole spectrum. On a signal
    whose entire diagnostic content is 'height of a narrow line above a
    broadband floor', raising the floor is precisely the wrong artefact.

    12000 -> 16000 becomes up=4, down=3 exactly; 12000 -> 6400 becomes
    up=8, down=15. Both are small integers, so the polyphase filters are cheap
    and no rate error accumulates.
    """
    if abs(fs_in - fs_out) < 1e-9:
        return np.asarray(x, dtype=np.float64)
    from scipy.signal import resample_poly
    frac = Fraction(fs_out / fs_in).limit_denominator(1000)
    return resample_poly(np.asarray(x, dtype=np.float64), frac.numerator,
                         frac.denominator).astype(np.float64)


def to_recording(rf: RawFile, fs_mode: str) -> Recording:
    """Map a RawFile onto the two channels firmware/features.py expects.

    fs_mode:
      "device" — resample to the production rates (16 kHz / 6.4 kHz). This is
                 the honest test: it is the configuration that will run on the
                 Pi, including the empty top octave that 12 kHz source data
                 leaves behind.
      "native" — keep 12 kHz on both channels. extract_features takes fs as an
                 argument, so this works unmodified. Use it to check that any
                 result is not an artefact of resampling.
    """
    if fs_mode == "device":
        fs_a, fs_v = FS_AUDIO_DEVICE, FS_ACCEL_DEVICE
    elif fs_mode == "native":
        fs_a = fs_v = rf.fs
    else:
        raise ValueError("fs_mode must be 'device' or 'native'")

    audio = resample_to(rf.de, rf.fs, fs_a)

    if rf.fe is not None and len(rf.fe) > 16:
        accel = resample_to(rf.fe, rf.fs, fs_v)
    else:
        # No fan-end channel: decimate DE into the accel slot. This is NOT a
        # second independent sensor — the two channels are then perfectly
        # correlated below 3.2 kHz, which makes 20 of the 40 features
        # near-duplicates of another 20. Ledoit-Wolf shrinkage keeps the
        # covariance invertible, but the effective dimensionality is lower than
        # it looks. The report flags every file this happened to.
        accel = resample_to(rf.de, rf.fs, fs_v)

    n = min(len(audio), int(len(accel) * fs_a / fs_v))
    audio = audio[:n]
    accel = accel[:int(n * fs_v / fs_a)]

    return Recording(audio=audio, fs_audio=fs_a,
                     accel=accel[:, None], fs_accel=fs_v,
                     meta={"rpm": rf.rpm, "source": rf.path.name},
                     path=rf.path)


# ============================================================================
# 3. Feature extraction over windows, with an honest train/test time split
# ============================================================================

def _windows(rec: Recording, window_s: float, hop_s: float,
             t0_frac: float, t1_frac: float):
    """Yield (audio, accel) window pairs from the [t0_frac, t1_frac) slice."""
    na, ha = int(window_s * rec.fs_audio), int(hop_s * rec.fs_audio)
    nv, hv = int(window_s * rec.fs_accel), int(hop_s * rec.fs_accel)
    a0, a1 = int(t0_frac * len(rec.audio)), int(t1_frac * len(rec.audio))
    v0 = int(t0_frac * len(rec.accel))
    i = 0
    while a0 + i * ha + na <= a1:
        yield (rec.audio[a0 + i * ha: a0 + i * ha + na],
               rec.accel[v0 + i * hv: v0 + i * hv + nv])
        i += 1


def feature_rows(rec: Recording, window_s: float, hop_s: float,
                 t0_frac: float = 0.0, t1_frac: float = 1.0):
    """(X, OP) for one time slice of one recording, via the SHIPPING feature
    extractor. Importing features here rather than reimplementing anything is
    the whole point — a validation that uses different code validates nothing.
    """
    from baseline import operating_point
    from features import extract_features

    X, OP = [], []
    for audio, accel in _windows(rec, window_s, hop_s, t0_frac, t1_frac):
        out = extract_features(audio, rec.fs_audio, accel, rec.fs_accel)
        X.append(out["vector"])
        OP.append(operating_point(out["vector"], out["fr_hz"]))
    if not X:
        return np.zeros((0, 40)), np.zeros((0, 3))
    return np.array(X), np.array(OP)


# ============================================================================
# 4. The envelope evidence — does BPFO actually show up on real data?
# ============================================================================

def envelope_evidence(rec: Recording, race: str, fr_hz: float,
                      window_s: float, bearing: str = CWRU_DRIVE_END_BEARING,
                      tol_pct: float = 3.0) -> dict:
    """Peak-to-background at the expected defect frequency in the ENVELOPE
    spectrum, using the shipping demodulator.

    tol_pct defaults to 3 % rather than the 2 % used on synthetic data because
    a real bearing under real load slips: the observed outer-race line on CWRU
    typically sits 1-2 % below the kinematic BPFO. A tolerance tighter than the
    slip would 'prove' the signature is absent when it is simply displaced.
    """
    geom = lookup(bearing)
    band, band_crest = choose_band(rec, window_s)
    freqs, mag = averaged_envelope_spectrum(rec, band, window_s)
    targets = {"BPFO": geom.bpfo(fr_hz), "BPFI": geom.bpfi(fr_hz),
               "BSF2x": geom.bsf_2x(fr_hz)}
    key = {"outer": "BPFO", "inner": "BPFI", "ball": "BSF2x"}.get(race or "", "BPFO")
    out = {"band": band, "band_crest": band_crest, "fr_hz": fr_hz,
           "expected": targets, "measured": {}}
    for name, hz in targets.items():
        out["measured"][name] = peak_to_background(freqs, mag, hz,
                                                   tol_pct=tol_pct, fr_hz=fr_hz)
    out["primary"] = key
    return out


def estimate_fr_from_rpm(rf: RawFile, rec: Recording) -> tuple[float, str]:
    """Shaft frequency in Hz. Prefer the rpm the dataset recorded; fall back to
    our own HPS estimator so files from stripped-down mirrors still work.

    Never guess silently: the source is returned and printed, because a wrong
    fr by 5 % moves BPFO by ~7 Hz and would make us search the wrong bin.
    """
    if rf.rpm and rf.rpm > 0:
        return rpm_to_hz(rf.rpm), rf.rpm_source
    from features import estimate_fr
    n = min(len(rec.audio), int(4 * rec.fs_audio))
    m = min(len(rec.accel), int(4 * rec.fs_accel))
    fr, reliable = estimate_fr(rec.audio[:n], rec.fs_audio,
                               rec.accel[:m], rec.fs_accel)
    return fr, ("estimated-reliable" if reliable else "estimated-UNRELIABLE")


# ============================================================================
# 5. Surrogate generator (plumbing test only — see module docstring)
# ============================================================================

def _pink(n: int, rng: np.random.Generator) -> np.ndarray:
    """1/f-ish noise by spectral shaping. Machinery noise floors are pink, not
    white; using white noise (as ml/simulate.py does) would make the high-
    frequency resonance band artificially quiet and detection artificially
    easy. Deliberately different from the simulator for that reason."""
    spec = np.fft.rfft(rng.standard_normal(n))
    f = np.arange(len(spec))
    spec /= np.sqrt(np.maximum(f, 1.0))
    x = np.fft.irfft(spec, n)
    return x / (np.std(x) + 1e-12)


def _surrogate_signal(fs: float, dur_s: float, rpm: float,
                      race: str | None, size_in: float,
                      rng: np.random.Generator) -> np.ndarray:
    """A motor-vibration signal written from scratch (does NOT import
    ml/simulate.py) so that agreement between the two is evidence rather than
    tautology.

    Model: 60 Hz mains hum + shaft harmonics + pink floor, plus, when faulty,
    a train of impacts at the kinematic defect frequency with slip jitter,
    each impact ringing TWO structural resonances with a double-exponential
    envelope. Inner-race and ball faults get 1x-shaft load-zone amplitude
    modulation; outer-race faults do not, because an outer-race defect is
    stationary with respect to the load zone.
    """
    n = int(dur_s * fs)
    t = np.arange(n) / fs
    fr = rpm / 60.0

    # Healthy background: shaft orders, 60 Hz US mains + its 2nd harmonic
    # (electromagnetic, present in every mains-fed induction motor), 2x-line
    # frequency slot noise, and a pink floor.
    sig = (1.00 * np.sin(2 * np.pi * fr * t + rng.uniform(0, 6.28))
           + 0.30 * np.sin(2 * np.pi * 2 * fr * t + rng.uniform(0, 6.28))
           + 0.12 * np.sin(2 * np.pi * 3 * fr * t + rng.uniform(0, 6.28))
           + 0.22 * np.sin(2 * np.pi * 60.0 * t + rng.uniform(0, 6.28))
           + 0.10 * np.sin(2 * np.pi * 120.0 * t + rng.uniform(0, 6.28)))
    sig = 0.06 * sig + 0.05 * _pink(n, rng)

    if race is None:
        return sig

    geom = lookup(CWRU_DRIVE_END_BEARING)
    f_def = {"outer": geom.bpfo, "inner": geom.bpfi,
             "ball": geom.bsf_2x}[race](fr)

    # Impact amplitude scales with defect width; 0.007" is the smallest CWRU
    # notch and is genuinely hard, 0.021" is obvious. Linear in size is a
    # guess, and it is only a surrogate, so it does not need to be right.
    amp = 0.9 * (size_in / 0.021)

    impacts = np.zeros(n)
    period = 1.0 / f_def
    tau = rng.uniform(0, period)
    while tau < dur_s:
        i = int(round(tau * fs))
        if i < n:
            a = 1.0
            if race in ("inner", "ball"):
                a = 0.35 + 0.65 * (0.5 + 0.5 * np.cos(2 * np.pi * fr * tau))
            impacts[i] += a * rng.uniform(0.7, 1.3)
        tau += period * (1.0 + rng.normal(0.0, 0.02))   # 2 % slip jitter

    from scipy.signal import lfilter
    burst = np.zeros(n)
    for f0, q, w in ((3400.0, 45.0, 1.0), (1150.0, 25.0, 0.35)):
        if f0 >= fs / 2:
            continue
        # Double-exponential ring: fast attack, slower decay. A pure 2nd-order
        # bandpass (what the simulator uses) has a symmetric-ish impulse
        # response; real impacts attack in microseconds.
        tt = np.arange(int(0.02 * fs)) / fs
        ir = (np.exp(-tt * np.pi * f0 / q) - np.exp(-tt * np.pi * f0 / (q / 6)))
        ir = ir * np.sin(2 * np.pi * f0 * tt)
        ir /= np.max(np.abs(ir)) + 1e-12
        burst += w * lfilter(ir, [1.0], impacts)

    return sig + amp * 0.05 * burst


def make_surrogate(out_dir: Path, dur_s: float = 10.0, fs: float = 12000.0,
                   seed: int = 7) -> Path:
    """Write a CWRU-shaped synthetic dataset: 4 normal files (one per load) and
    9 fault files (3 races x 3 sizes at 1 hp/2 hp/3 hp mixed)."""
    from scipy.io import savemat

    out_dir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)
    rpms = {0: 1797.0, 1: 1772.0, 2: 1750.0, 3: 1730.0}
    written = []

    def _write(name: str, num: int, race: str | None, size: float, load: int):
        rpm = rpms[load]
        de = _surrogate_signal(fs, dur_s, rpm, race, size, rng)
        # Fan end sees the same machine through more structure: attenuated,
        # low-passed, and with its own independent noise. Not a copy of DE.
        from scipy.signal import butter, sosfilt
        sos = butter(3, 2500.0, btype="low", fs=fs, output="sos")
        fe = 0.45 * sosfilt(sos, de) + 0.03 * _pink(len(de), rng)
        savemat(str(out_dir / name), {
            f"X{num:03d}_DE_time": de.reshape(-1, 1),
            f"X{num:03d}_FE_time": fe.reshape(-1, 1),
            f"X{num:03d}RPM": np.array([[rpm]]),
        })
        written.append(name)

    for load in range(4):
        _write(f"Normal_{load}.mat", 97 + load, None, 0.0, load)
    num = 105
    for race, code in (("inner", "IR"), ("outer", "OR"), ("ball", "B")):
        for size in (0.007, 0.014, 0.021):
            load = (num - 105) % 4
            _write(f"{code}{int(size * 1000):03d}_{load}.mat", num, race, size, load)
            num += 1

    (out_dir / "README_SURROGATE.txt").write_text(
        "SYNTHETIC SURROGATE — NOT REAL DATA.\n"
        "Generated by ml/realdata/validate_public_dataset.py --make-surrogate.\n"
        "It mimics the CWRU on-disk format so the loading/resampling/fitting/\n"
        "scoring path can be executed without network access. Any metric\n"
        "computed on these files tests the CODE, not the physics.\n"
        "Delete this directory and use the real dataset before quoting a number.\n")
    print(f"wrote {len(written)} surrogate files to {out_dir}")
    return out_dir


