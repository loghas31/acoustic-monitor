# 6. The run
# ============================================================================

@dataclass
class Config:
    data_dir: Path
    out_dir: Path
    window_s: float = 1.0
    train_hop_s: float = 0.5
    train_frac: float = 0.6
    fs_mode: str = "device"
    default_fs: float = 12000.0
    tol_pct: float = 3.0
    surrogate: bool = False
    max_faulty_files: int = 0          # 0 = all
    notes: list[str] = field(default_factory=list)


def run(cfg: Config) -> dict:
    from sklearn.metrics import roc_auc_score

    from baseline import fit_baseline, save_baseline
    from features import FEATURE_NAMES
    from inference import MahalanobisScorer

    tag = "[SURROGATE] " if cfg.surrogate else ""
    print(f"\n{'=' * 78}\n{tag}Public-dataset validation — {cfg.data_dir}\n{'=' * 78}")

    # The surrogate warning is stamped HERE, not in main(), so that the JSON is
    # labelled no matter which entry point produced it. A synthetic result that
    # loses its label on the way to disk is the exact failure mode this whole
    # script is meant to prevent.
    if cfg.surrogate and not any("SURROGATE" in n for n in cfg.notes):
        cfg.notes.append(
            "SYNTHETIC SURROGATE — proves the code path, not the physics.")

    files = discover(cfg.data_dir, cfg.default_fs)
    if not files:
        raise SystemExit(f"no .mat/.npz/.csv files under {cfg.data_dir}")

    healthy = [f for f in files if f.label == 0]
    faulty = [f for f in files if f.label == 1]
    if cfg.max_faulty_files:
        faulty = faulty[:cfg.max_faulty_files]

    print(f"\n--- files found ({len(files)}) "
          f"[{len(healthy)} healthy, {len(faulty)} faulty] ---")
    for f in files:
        print("  " + f.describe())

    if not healthy or not faulty:
        raise SystemExit(
            "need at least one healthy AND one faulty file. Check the "
            "classification table above; add a manifest.csv to override.")

    no_fe = [f.path.name for f in files if f.fe is None]
    if no_fe:
        cfg.notes.append(
            f"{len(no_fe)} file(s) had no fan-end channel; the accel slot was "
            f"filled with a decimated copy of DE (correlated channels): "
            f"{', '.join(no_fe[:4])}{'...' if len(no_fe) > 4 else ''}")

    # ---- healthy: time-split into train / held-out -------------------------
    print(f"\n--- extracting features "
          f"(window {cfg.window_s:g} s, fs_mode={cfg.fs_mode}) ---")
    Xtr, OPtr = [], []
    Xho, OPho = [], []
    for f in healthy:
        rec = to_recording(f, cfg.fs_mode)
        a, b = feature_rows(rec, cfg.window_s, cfg.train_hop_s, 0.0, cfg.train_frac)
        c, d = feature_rows(rec, cfg.window_s, cfg.window_s, cfg.train_frac, 1.0)
        Xtr.append(a); OPtr.append(b)
        Xho.append(c); OPho.append(d)
        print(f"  {f.path.name:<24} train {len(a):3d} windows (overlapped)   "
              f"held-out {len(c):3d} windows (disjoint)")
    Xtr, OPtr = np.vstack(Xtr), np.vstack(OPtr)
    Xho, OPho = np.vstack(Xho), np.vstack(OPho)

    # ---- faulty: no overlap, all of it is test -----------------------------
    Xf, OPf, fault_index = [], [], []
    for f in faulty:
        rec = to_recording(f, cfg.fs_mode)
        a, b = feature_rows(rec, cfg.window_s, cfg.window_s, 0.0, 1.0)
        if len(a) == 0:
            continue
        Xf.append(a); OPf.append(b)
        fault_index += [f.path.name] * len(a)
        print(f"  {f.path.name:<24} faulty {len(a):3d} windows (disjoint)")
    Xf, OPf = np.vstack(Xf), np.vstack(OPf)

    print(f"\n  learn period : {len(Xtr)} windows from {len(healthy)} healthy file(s)")
    print(f"  held-out ok  : {len(Xho)} windows")
    print(f"  faulty       : {len(Xf)} windows from {len(faulty)} file(s)")

    # ---- fit the baseline on healthy only ----------------------------------
    b = fit_baseline(Xtr, OPtr, list(FEATURE_NAMES))
    cfg.out_dir.mkdir(parents=True, exist_ok=True)
    bpath = cfg.out_dir / "public_baseline.npz"
    save_baseline(bpath, b)
    print(f"\n--- baseline fitted ---")
    print(f"  regimes k = {b['k']}  counts {np.asarray(b['counts']).tolist()}  "
          f"thresholds {np.round(b['thresholds'], 2).tolist()}")

    scorer = MahalanobisScorer(bpath)
    s_ho = np.array([scorer.score(x, op)["score"] for x, op in zip(Xho, OPho)])
    s_f = np.array([scorer.score(x, op)["score"] for x, op in zip(Xf, OPf)])
    r_ho = np.array([scorer.score(x, op)["regime"] for x, op in zip(Xho, OPho)])
    thr_ho = np.array([scorer.thresholds[r] for r in r_ho])
    r_f = np.array([scorer.score(x, op)["regime"] for x, op in zip(Xf, OPf)])
    thr_f = np.array([scorer.thresholds[r] for r in r_f])

    y = np.r_[np.zeros(len(s_ho)), np.ones(len(s_f))]
    auc = float(roc_auc_score(y, np.r_[s_ho, s_f]))
    fpr = float(np.mean(s_ho > thr_ho))
    tpr = float(np.mean(s_f > thr_f))

    print(f"\n--- DETECTION (held-out healthy vs faulty) ---")
    print(f"  ROC AUC                       : {auc:.4f}")
    print(f"  healthy median score          : {np.median(s_ho):.2f}   "
          f"(threshold median {np.median(thr_ho):.2f})")
    print(f"  faulty  median score          : {np.median(s_f):.2f}")
    print(f"  false-positive rate at learned threshold : {fpr:.3f}")
    print(f"  true-positive  rate at learned threshold : {tpr:.3f}")

    # per-file recall — one bad file should not hide behind nine good ones
    print(f"\n  per-file true-positive rate:")
    per_file = {}
    for name in dict.fromkeys(fault_index):
        m = np.array([n == name for n in fault_index])
        per_file[name] = float(np.mean(s_f[m] > thr_f[m]))
        print(f"    {name:<24} {per_file[name]:.2f}  "
              f"(median score {np.median(s_f[m]):.1f})")

    # ---- envelope evidence on the largest fault of each race ---------------
    print(f"\n--- ENVELOPE EVIDENCE (shipping demodulator, real geometry) ---")
    evidence = {}
    seen: set[str] = set()
    for f in faulty:
        if not f.race or f.race in seen:
            continue
        seen.add(f.race)
        rec = to_recording(f, cfg.fs_mode)
        fr, src = estimate_fr_from_rpm(f, rec)
        ev = envelope_evidence(rec, f.race, fr, cfg.window_s, tol_pct=cfg.tol_pct)
        key = ev["primary"]
        m = ev["measured"][key]
        evidence[f.path.name] = {"race": f.race, "fr_hz": fr, "fr_source": src,
                                 "band": list(ev["band"]),
                                 "target": key,
                                 "expected_hz": ev["expected"][key],
                                 **{k: v for k, v in m.items() if k != "excluded_hz"}}
        print(f"  {f.path.name:<22} {f.race:<6} fr={fr:6.2f} Hz ({src})")
        print(f"      band {ev['band'][0]:.0f}-{ev['band'][1]:.0f} Hz "
              f"(crest {ev['band_crest']:.1f}) | {key} expected "
              f"{ev['expected'][key]:.2f} Hz")
        if m["confounded"] or not np.isfinite(m["ratio"]):
            print(f"      -> NO CLEAN MEASUREMENT: {m['note']}")
        else:
            print(f"      -> peak at {m['peak_hz']:.2f} Hz "
                  f"(slip {m['slip_pct']:+.2f} %), "
                  f"peak/background = {m['ratio']:.1f}x")

    # healthy control: the same measurement where there is no defect
    hrec = to_recording(healthy[0], cfg.fs_mode)
    hfr, hsrc = estimate_fr_from_rpm(healthy[0], hrec)
    hev = envelope_evidence(hrec, "outer", hfr, cfg.window_s, tol_pct=cfg.tol_pct)
    hm = hev["measured"]["BPFO"]
    print(f"  {healthy[0].path.name:<22} CONTROL (healthy) fr={hfr:.2f} Hz "
          f"-> BPFO peak/background = {hm['ratio']:.1f}x")
    print(f"      A fault is only evidence if this control number is SMALL.")

    result = {
        "surrogate": cfg.surrogate,
        "data_dir": str(cfg.data_dir),
        "fs_mode": cfg.fs_mode,
        "window_s": cfg.window_s,
        "n_healthy_files": len(healthy), "n_faulty_files": len(faulty),
        "n_train_windows": int(len(Xtr)),
        "n_heldout_windows": int(len(Xho)),
        "n_faulty_windows": int(len(Xf)),
        "k_regimes": int(b["k"]),
        "roc_auc": auc, "fpr_at_threshold": fpr, "tpr_at_threshold": tpr,
        "healthy_median_score": float(np.median(s_ho)),
        "faulty_median_score": float(np.median(s_f)),
        "per_file_tpr": per_file,
        "envelope_evidence": evidence,
        "healthy_control_bpfo_ratio": float(hm["ratio"]),
        "notes": cfg.notes,
    }
    jpath = cfg.out_dir / "public_dataset_result.json"
    jpath.write_text(json.dumps(result, indent=2, default=float))
    print(f"\n  wrote {jpath}")

    if cfg.notes:
        print("\n--- caveats recorded ---")
        for n in cfg.notes:
            print(f"  * {n}")
    if cfg.surrogate:
        print("\n" + "!" * 78)
        print("!! THESE NUMBERS COME FROM A SYNTHETIC SURROGATE, NOT REAL DATA.")
        print("!! They demonstrate that the code path runs correctly end to end.")
        print("!! They say NOTHING about whether the detector works on a real")
        print("!! machine. Re-run with --data-dir <real CWRU download>.")
        print("!" * 78)
    return result


