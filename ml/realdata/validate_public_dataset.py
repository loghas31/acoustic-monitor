"""
validate_public_dataset.py — run a PUBLIC, REAL, seeded-fault bearing dataset
through this project's own pipeline, end to end, and report what happens.

WHY THIS SCRIPT IS THE MOST IMPORTANT ONE IN ml/
--------------------------------------------------------------------------
Every performance number this project owns (ROC AUC 1.000, 0 false alarms,
56.7x envelope contrast) was produced on signals generated by `ml/simulate.py`
— which was written by the same people, using the same assumed physics, as the
detector it is testing. That is a closed loop. It cannot falsify itself.

This script opens the loop. It takes vibration recorded from a REAL motor with
a REAL EDM-machined bearing defect, and pushes it through the EXACT shipping
code path:

    features.extract_features   ->  baseline.fit_baseline  (healthy only)
                                ->  inference.MahalanobisScorer  (held out)

If the detector only works on our own simulation, this is where it shows.

    python ml/realdata/validate_public_dataset.py --data-dir path/to/cwru
    python ml/realdata/validate_public_dataset.py --help-download   # how to get it


WHICH DATASET, AND WHY
--------------------------------------------------------------------------
**Case Western Reserve University (CWRU) Bearing Data Center.** Chosen over
the alternatives for one decisive reason: it is the only one of the three that
is a plain HTTP directory of small Matlab files with no registration wall, so a
student can have it on disk in five minutes.

  * CWRU  — 2 hp Reliance Electric motor, SKF 6205-2RS JEM drive-end bearing,
            EDM seeded faults 0.007"-0.040" on inner race / ball / outer race,
            4 motor loads (0-3 hp, 1797-1720 rpm), 12 kHz and 48 kHz.
            https://engineering.case.edu/bearingdatacenter
  * Paderborn KAt — better dataset scientifically (it includes REAL
            accelerated-life damage, not only EDM cuts, which is exactly the
            criticism levelled at CWRU). But it is ~20 GB of .mat behind a
            university download form. Worth doing later; too heavy for a first
            check. Use `--layout paderborn`-style extension when you get there.
  * MFPT — small and clean, but only 3 fault conditions and no load sweep, so
            it cannot exercise our multi-REGIME machinery at all.

**Known weakness of CWRU, stated up front:** the faults are single-point EDM
notches, which are far more impulsive than a real spall that has grown over
months. Detection here is therefore EASIER than reality — a good AUC on CWRU is
a necessary condition for the product working, not a sufficient one. Several
published re-analyses also flag that a handful of CWRU files are mislabelled or
contaminated; we mitigate by never relying on a single file (see `--min-files`).

LICENCE / CITATION — READ BEFORE PUBLISHING ANY NUMBER FROM THIS
--------------------------------------------------------------------------
As of 2026-08-16 the Bearing Data Center pages publish the files openly but
state **no formal licence** — the site footer carries only "(c) Case Western
Reserve University". There is no CC-BY grant. Practical consequences:

  1. **Acknowledge the source** in the report, the pitch deck, and any paper:
     "Data provided by the Case Western Reserve University Bearing Data Center,
     https://engineering.case.edu/bearingdatacenter (accessed <date>)."
  2. **Do NOT commit the .mat files into this repository.** Absent an explicit
     licence, redistribution is not clearly permitted. This script therefore
     takes `--data-dir` and never vendors data. Add the download directory to
     .gitignore.
  3. If the work is ever published, ask the Data Center for written permission.
     Students routinely do; it costs one email.

THE SAMPLE-RATE / CHANNEL MISMATCH, AND THE CHOICE WE MADE
--------------------------------------------------------------------------
Our product samples a MICROPHONE at 16 kHz and an ACCELEROMETER at 6.4 kHz.
CWRU has no microphone at all: it is two (sometimes three) accelerometers at
12 kHz (or 48 kHz for some drive-end sets). So the mapping is not obvious and
it is not free. What we do, and why:

    CWRU drive-end accel (DE)  ->  our "audio"  slot, resampled 12k -> 16 kHz
    CWRU fan-end   accel (FE)  ->  our "accel"  slot, resampled 12k -> 6.4 kHz

Justification: our "audio" slot is simply *the wideband channel* — it is the
one the protrugram searches for a resonance and the one the envelope spectrum
is computed from. DE is the channel physically closest to the defective
bearing and the one with the bandwidth, so DE belongs in that slot. FE is a
genuinely different sensor at a different location, which is the right analogue
of our second channel.

Three honest consequences, all of which the report prints:

  1. **Absolute units differ.** DE is in g, a microphone is in arbitrary
     normalised units. This does not matter: every feature is either
     dimensionless (band-energy *ratios*, kurtosis, crest) or is compared only
     against a baseline learned from the same channel (log-RMS). The detector
     is relative to itself by construction. But do not compare a log-RMS
     printed here with one printed by firmware/features.py.
  2. **We lose the top octave.** 12 kHz sampling means a 6 kHz Nyquist, so
     after resampling to 16 kHz the 6-8 kHz analysis bins are empty. Those
     become near-constant features, which contribute nothing to the Mahalanobis
     distance in either direction (Ledoit-Wolf keeps the covariance
     invertible). Effect: we test a slightly *narrower*-band version of our
     detector than ships. `--fs-mode native` skips resampling entirely and runs
     the features at 12 kHz, so you can confirm the answer is not a resampling
     artefact. Run both; the report tells you if they disagree.
  3. **Window length.** Production uses 30 s windows; CWRU files are only
     ~10 s. We use 1 s windows by default. At 1797 rpm that is ~30 shaft
     revolutions and ~107 outer-race impacts — ample for envelope statistics,
     which is the quantity that actually needs the duration.

INDEPENDENCE OF THE EVALUATION (the part that is easy to get wrong)
--------------------------------------------------------------------------
Overlapping windows are not independent samples, and an AUC computed across
them is optimistic. We therefore split by TIME first:

    healthy file  |<---- first 60%: TRAIN ---->|<--- last 40%: HELD OUT --->|

Overlapping hops are permitted inside the TRAIN segment only (more windows
genuinely helps estimate a 40x40 covariance from a 6 s slice, and there is no
metric computed on them). The held-out healthy segment and every faulty file
are windowed with NO overlap. So no sample that contributed to the model
appears in any reported number.

NO NETWORK? --surrogate
--------------------------------------------------------------------------
The development sandbox this project is built in has no outbound DNS, so the
dataset cannot be fetched here. `--make-surrogate DIR` writes a synthetic
dataset in the CWRU on-disk format (same variable names, same 12 kHz, same
rpm/load structure) so that every line of the loading, resampling, splitting,
fitting and scoring path can be executed and tested.

    **A result on the surrogate proves the PLUMBING, not the PHYSICS.**

The surrogate signal model is deliberately written from scratch in this file
and does NOT import ml/simulate.py — different noise colour (pink, not
band-limited white), different mains frequency (60 Hz US, not 50 Hz),
two resonances instead of one, double-exponential impact shape, load-zone AM,
and per-load rpm. That makes it an independent implementation, which is worth
something as a plumbing test. It is still not real data, and the report labels
every surrogate number `[SURROGATE]` in capitals for exactly that reason.
"""

