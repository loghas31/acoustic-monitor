def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Validate the detector on a public real bearing dataset.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=HELP_DOWNLOAD)
    p.add_argument("--data-dir", type=Path,
                   help="directory of CWRU .mat (or .npz/.csv) files")
    p.add_argument("--out-dir", type=Path, default=_HERE / "output",
                   help="where the baseline and result JSON are written")
    p.add_argument("--window-s", type=float, default=1.0,
                   help="analysis window (default 1.0 s; CWRU files are ~10 s "
                        "so the production 30 s window is impossible)")
    p.add_argument("--train-hop-s", type=float, default=0.5,
                   help="hop inside the TRAIN slice only (overlap allowed there)")
    p.add_argument("--train-frac", type=float, default=0.6,
                   help="fraction of each healthy file used to learn")
    p.add_argument("--fs-mode", choices=("device", "native"), default="device",
                   help="'device' resamples to 16 kHz/6.4 kHz (production); "
                        "'native' keeps the dataset rate")
    p.add_argument("--default-fs", type=float, default=12000.0,
                   help="sample rate for files that do not carry one (CWRU 12k "
                        "sets = 12000; the 48k drive-end sets = 48000)")
    p.add_argument("--tol-pct", type=float, default=3.0,
                   help="slip tolerance when searching for the defect line")
    p.add_argument("--max-faulty-files", type=int, default=0,
                   help="cap the number of fault files (0 = all)")
    p.add_argument("--make-surrogate", type=Path, metavar="DIR",
                   help="write a SYNTHETIC CWRU-format dataset to DIR and "
                        "validate against it (plumbing test, not physics)")
    p.add_argument("--surrogate-duration", type=float, default=10.0)
    p.add_argument("--help-download", action="store_true",
                   help="print dataset download instructions and exit")
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    if args.help_download:
        print(HELP_DOWNLOAD)
        return 0

    surrogate = False
    if args.make_surrogate:
        make_surrogate(args.make_surrogate, dur_s=args.surrogate_duration)
        data_dir = args.make_surrogate
        surrogate = True
    elif args.data_dir:
        data_dir = args.data_dir
    else:
        print(HELP_DOWNLOAD)
        print("ERROR: give --data-dir <downloaded dataset>, or --make-surrogate "
              "<dir> to exercise the code path without network access.")
        return 2

    if not data_dir.exists():
        print(f"ERROR: {data_dir} does not exist. Run --help-download.")
        return 2

    cfg = Config(data_dir=data_dir, out_dir=args.out_dir,
                 window_s=args.window_s, train_hop_s=args.train_hop_s,
                 train_frac=args.train_frac, fs_mode=args.fs_mode,
                 default_fs=args.default_fs, tol_pct=args.tol_pct,
                 surrogate=surrogate,
                 max_faulty_files=args.max_faulty_files)
    run(cfg)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
